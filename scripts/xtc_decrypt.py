# 加密文件特征头（前20字节）
ENCRYPTED_MAGIC = bytes([
    0xE7, 0xDD, 0x3B, 0x60, 0x6F, 0x74, 0xA4, 0xE3,
    0x64, 0xC4, 0xC8, 0x7E, 0x32, 0x2D, 0xA9, 0xA3,
    0x41, 0xA3, 0x9B, 0xE5,
])


def decrypt_file(input_path: str, output_path: str = None) -> bool:
    """
    解密单个加密 XML 文件。
    output_path 为 None 时原地覆盖（与 MIO-KITCHEN 原行为一致）。
    返回是否解密成功。
    """
    if not os.path.exists(input_path):
        print(f"  [跳过] 文件不存在: {input_path}")
        return False

    filesize = os.path.getsize(input_path)

    # 检查是否为加密文件（前20字节匹配）
    with open(input_path, 'rb') as f:
        header = f.read(20)
    if header != ENCRYPTED_MAGIC:
        print(f"  [跳过] 非加密文件（头部不匹配）: {input_path}")
        return False

    # 初始参数（固定，不从文件读取）
    index = 41
    count = 41
    unknow4 = 0

    with open(input_path, 'rb') as f:
        # >32KB 只解密前32字节，否则全文解密
        buffer_size = 32 if filesize > 0x8000 else filesize
        buffer = bytearray(f.read(buffer_size))

    cur = 0
    while cur < buffer_size:
        key_index = (cur + unknow4) % 64
        buffer[cur] ^= key_table[key_index]
        buffer[cur] ^= key_table[index]
        if key_index == 0:
            count += 1
            index += 1
            if count >= 256:
                count = 0
                index = 0
        cur += 1

    # 写回
    target = output_path if output_path else input_path
    os.makedirs(os.path.dirname(target) if os.path.dirname(target) else '.', exist_ok=True)
    with open(target, 'wb') as f:
        f.write(buffer)

    # 验证解密结果（前5字节应为 <?xml）
    if buffer[:5] == b'<?xml':
        print(f"  [成功] {os.path.basename(input_path)} ({filesize}B) -> {target}")
        return True
    else:
        print(f"  [警告] 解密结果不以 <?xml 开头: {target}")
        return False


def decrypt_path(path: str, output_dir: str = None):
    """解密文件或目录下所有加密 XML"""
    if os.path.isfile(path):
        out = os.path.join(output_dir, os.path.basename(path)) if output_dir else None
        decrypt_file(path, out)
    elif os.path.isdir(path):
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)
        for fname in sorted(os.listdir(path)):
            if fname.lower().endswith('.xml'):
                fpath = os.path.join(path, fname)
                out = os.path.join(output_dir, fname) if output_dir else None
                decrypt_file(fpath, out)
    else:
        print(f"路径不存在: {path}")


